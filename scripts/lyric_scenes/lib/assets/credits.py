"""ASSETS.md + the video-description credits block, generated from what the build actually LOADED (plain python3 -I).

    python3 -I credits.py --used OUT/import_log.json [--used ...] [--asset-dir DIR ...] [--use SLUG="hero dragon" ...]
                          --out scripts/lyric_scenes/real/<scene>/ASSETS.md [--title "Boss Fight"] [--force]
    python3 -I credits.py --audit /data/iris_assets          # read-only: every SOURCE.json, canonical licence, verdict

* --used: lib/importer.write_log() output ({"imports": [...], "files": [...]}); every file under /data/iris_assets is
  traced up to its nearest SOURCE.json (any of the legacy shapes — licence.normalize). Files outside /data/iris_assets
  are our own (generated/procedural) and not credited. A third-party file with NO SOURCE.json is an ERROR.
* GATE: every used asset must be CC0 or CC-BY (map data ODbL/Copernicus allowed with their attribution line). Anything
  else (BY-SA / NC / ND / unknown) → exit 2, nothing written, with the reason per asset.
* Every CC-BY asset MUST have an author and a URL (it goes in the video description) → else exit 2.
* Refuses to overwrite an ASSETS.md it did not generate (hand-written ones) unless --force.
"""
import argparse
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import licence  # noqa: E402

ASSET_ROOT = "/data/iris_assets"
MARK = "<!-- generated by scripts/lyric_scenes/lib/assets/credits.py — edit the inputs, not this file -->"


def used_files(logs):
    files = []
    for p in logs:
        with open(p) as f:
            d = json.load(f)
        if isinstance(d, dict):
            files += d.get("files", []) + [r["path"] for r in d.get("imports", [])]
        else:                                     # a bare LOG list
            files += [r["path"] for r in d]
    return sorted(set(os.path.abspath(f) for f in files))


def collect(files, asset_dirs=(), root=ASSET_ROOT):
    """→ (sources {source_path: {"src": normalized, "files": [...]}}, unsourced [files], own [files])"""
    sources, unsourced, own = {}, [], []
    for f in files:
        if not f.startswith(os.path.abspath(root).rstrip("/") + "/"):
            own.append(f)
            continue
        sp = licence.find_source(f, root)
        if sp is None:
            unsourced.append(f)
            continue
        sources.setdefault(sp, {"src": licence.load(sp), "files": []})["files"].append(f)
    for d in asset_dirs:
        sp = os.path.join(os.path.abspath(d), "SOURCE.json")
        if not os.path.isfile(sp):
            unsourced.append(d)
            continue
        sources.setdefault(sp, {"src": licence.load(sp), "files": []})
    return sources, unsourced, own


def problems(sources, unsourced):
    errs = []
    for f in unsourced:
        errs.append(f"NO SOURCE.json for third-party file {f} — add one (fetch.py writes it) before delivery")
    for sp, e in sorted(sources.items()):
        s = e["src"]
        ok, c, why = licence.gate(s["licence_label"] if s["licence"] == "unknown" else s["licence"], data_ok=True)
        if not ok:
            errs.append(f"{s['name']} ({sp}): {why}")
        if c == "CC-BY" and not (s.get("author") and s.get("url")):
            errs.append(f"{s['name']} ({sp}): CC-BY needs author AND url for the credits block "
                        f"(author={s.get('author')!r}, url={s.get('url')!r})")
    return errs


def _slug(sp):
    return os.path.basename(os.path.dirname(sp))


def render_md(sources, own, title, uses=None):
    uses = uses or {}
    rows = sorted(sources.items(), key=lambda kv: ({"CC-BY": 0, "CC0": 1}.get(kv[1]["src"]["licence"], 2),
                                                    (kv[1]["src"]["name"] or "").lower()))
    out = [MARK, f"# {title} — assets, licences, credits", "",
           f"Licence policy: **{' + '.join(licence.ALLOWED_LICENCES)} only** (Zeke 2026-10-15); map data with its "
           "attribution. Generated from the build's import log — every row was actually loaded.", "",
           "| Asset | Site | Author | Licence | Used for | Files | Folder |", "|---|---|---|---|---|---|---|"]
    for sp, e in rows:
        s = e["src"]
        name = f"[{s['name']}]({s['url']})" if s.get("url") else (s["name"] or "?")
        author = f"[{s['author']}]({s['author_url']})" if s.get("author") and s.get("author_url") else (s.get("author") or "—")
        lic = f"[{s['licence']}]({s['licence_url']})" if s.get("licence_url") else s["licence"]
        out.append(f"| {name} | {s['site']} | {author} | {lic} | {uses.get(_slug(sp), '')} | {len(e['files']) or '—'} "
                   f"| `{os.path.dirname(sp)}` |")
    by = [e["src"] for _, e in rows if e["src"]["licence"] == "CC-BY"]
    data = [e["src"] for _, e in rows if e["src"]["licence"] in licence.DATA_LICENCES]
    cc0 = sorted({(e["src"]["author"] or e["src"]["site"]) for _, e in rows if e["src"]["licence"] == "CC0"})
    out += ["", "## Credits block (paste into the video description)", "", "```"]
    if by:
        out.append("3D models (CC BY 4.0 — https://creativecommons.org/licenses/by/4.0/):")
        out += [f"• \"{s['name']}\" by {s['author']} — {s['url']}" for s in by]
    for s in data:
        out.append(f"• {s.get('attribution') or s['name']} ({s['licence']})")
    if cc0:
        out.append("CC0 assets (no credit required — thank you): " + ", ".join(cc0))
    out += ["```", ""]
    if own:
        out += [f"Own/generated files used (not credited): {len(own)}", ""]
    return "\n".join(out)


def audit(root):
    rows = []
    for p in sorted(glob.glob(os.path.join(root, "**", "SOURCE.json"), recursive=True)):
        try:
            s = licence.load(p)
        except Exception as e:  # noqa: BLE001
            rows.append((p, "UNREADABLE", False, str(e)))
            continue
        ok, c, why = licence.gate(s["licence_label"] if s["licence"] == "unknown" else s["licence"], data_ok=True)
        if ok and c == "CC-BY" and not (s.get("author") and s.get("url")):
            ok, why = False, "CC-BY without author/url"
        rows.append((p, c, ok, why))
    return rows


def _main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--used", action="append", default=[])
    ap.add_argument("--asset-dir", action="append", default=[])
    ap.add_argument("--use", action="append", default=[], help='SLUG="what it is used for"')
    ap.add_argument("--out")
    ap.add_argument("--title", default="Scene")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--audit")
    ap.add_argument("--root", default=ASSET_ROOT)
    a = ap.parse_args(argv)
    if a.audit:
        rows = audit(a.audit)
        from collections import Counter
        bad = [r for r in rows if not r[2]]
        for p, c, ok, why in bad:
            print(f"[credits] BLOCKED {c:10s} {p}: {why}")
        print(f"[credits] audit {len(rows)} SOURCE.json: " + ", ".join(f"{k} {v}" for k, v in Counter(r[1] for r in rows).most_common())
              + f" — {len(bad)} blocked")
        return rows
    sources, unsourced, own = collect(used_files(a.used), a.asset_dir, a.root)
    errs = problems(sources, unsourced)
    if errs:
        for e in errs:
            print(f"[credits] ERROR {e}", file=sys.stderr)
        sys.exit(2)
    uses = dict(u.split("=", 1) for u in a.use)
    md = render_md(sources, own, a.title, uses)
    if a.out in (None, "-"):
        print(md)
        return md
    if os.path.exists(a.out) and not a.force:
        with open(a.out) as f:
            hand_written = MARK not in f.read()
    else:
        hand_written = False
    if hand_written:
        sys.exit(f"[credits] REFUSED: {a.out} is hand-written (no generator marker) — pass --force or pick another --out")
    with open(a.out, "w") as f:
        f.write(md)
    print(f"[credits] wrote {a.out}: {len(sources)} sources "
          f"({sum(1 for e in sources.values() if e['src']['licence'] == 'CC-BY')} CC-BY credited), {len(own)} own files")
    return md


if __name__ == "__main__":
    _main(sys.argv[1:])
